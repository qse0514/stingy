export const stingy: AgentConfig = {
  name: 'stingy',
  systemPrompt: STINGY_PROMPT,
  // ⭐ 权限写在这里，一眼能看完。想收权就从这个清单里删掉一项，不用去改 prompt
  tools: pickTools(
    'get_time',
    'add_expense',
    'query_expenses',
    'update_expense',
    'delete_expense',
    'restore_expense',
    'set_budget',      // 🗄️ W12 D4：预算
    'query_budget',
  ),
};

// 🤖 ⭐ 只读 Stingy：查账 / 分析 / 闲聊 走这个。没有任何写库的工具
//    它能不能记账，不取决于它愿不愿意，取决于它的申请表上有没有这一项
export const stingyReadonly: AgentConfig = {
  name: 'readonly',
  systemPrompt: [
    STINGY_PROMPT,
    // 🤖 告知它现状，否则它会反复尝试一个不存在的工具，浪费轮数
    '当前处于只读模式，你没有记账工具，也没有修改/删除工具。用户要记账或要改账时，直接告诉他需要先确认开启，不要假装已经做了。',
  ].join('\n'),
  tools: pickTools('get_time', 'query_expenses'), // ⭐ 少的那几项就是整个隔离
};

